# compact_product.py - make the compact copy of a product script that the brain downloads.
#
# Why: the brain runs product.py with exec(open(...).read()), so the WHOLE source
# text sits in the Pico's RAM while it compiles and while the product runs
# (DEV-236: the 45 KB Smart Alarm Maxi crashed with MemoryError). Comments,
# docstrings and indentation are useless to the Pico, so we ship a copy without
# them. The readable source stays in scripts/src/ - that is the one to read and edit.
#
#   python tools/compact_product.py scripts/src/smart_alarm_maxi.py scripts/smart_alarm_maxi.py
#
# How: parse with Python's own ast, drop docstrings, print it back (ast.unparse
# drops every comment), indent with ONE space per level. Strings are printed as
# single-line literals, so re-indenting can never change a string. The result is
# checked: it must compile and produce the same bytecode-level AST as the source.
import ast
import sys

HEADER = ("# SPDX-License-Identifier: MIT\n"
          "# GENERATED by tools/compact_product.py from {src} - do not edit this file,\n"
          "# edit the source and regenerate. Compact copy: no comments (Pico RAM, DEV-236).\n")


class _DropDocstrings(ast.NodeTransformer):
    def _strip(self, node):
        self.generic_visit(node)
        body = node.body
        if body and isinstance(body[0], ast.Expr) and isinstance(getattr(body[0], "value", None), ast.Constant) \
                and isinstance(body[0].value.value, str):
            body = body[1:] or [ast.Pass()]
        node.body = body
        return node
    visit_Module = visit_FunctionDef = visit_ClassDef = visit_AsyncFunctionDef = _strip


def compact(src_text):
    tree = _DropDocstrings().visit(ast.parse(src_text))
    out = []
    for line in ast.unparse(tree).splitlines():
        if not line.strip():
            continue
        n = len(line) - len(line.lstrip(" "))
        out.append(" " * (n // 4) + line.lstrip(" "))
    return "\n".join(out) + "\n"


def main(src, dst):
    text = open(src, encoding="utf-8").read()
    small = compact(text)
    # Same program? Compare the ASTs (docstrings removed from both).
    a = ast.dump(_DropDocstrings().visit(ast.parse(text)))
    b = ast.dump(ast.parse(small))
    if a != b:
        raise SystemExit("compact copy differs from the source - not written")
    small = HEADER.format(src=src.replace("\\", "/")) + small
    with open(dst, "w", encoding="utf-8", newline="\n") as f:
        f.write(small)
    print("%s: %d bytes -> %s: %d bytes" % (src, len(text.encode()), dst, len(small.encode())))


if __name__ == "__main__":
    if len(sys.argv) != 3:
        raise SystemExit(__doc__ or "usage: compact_product.py SRC DST")
    main(sys.argv[1], sys.argv[2])
